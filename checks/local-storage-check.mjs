import assert from "node:assert/strict";
import "fake-indexeddb/auto";
import { loadLocalNotebook, saveLocalNotebook, RevisionConflict } from "../lib/local-notebook.ts";
import { newBookshelf } from "../lib/notebook.ts";
assert.equal(await loadLocalNotebook(), null);
const a = newBookshelf(); a.books[0].title = "기기 저장 확인"; a.books[0].pages[0].text = "저장할 글 2026 abc.";
a.books[0].pages[0].strokes = [{ id: "ink", color: "#274e80", width: 2, points: [{ x: .2, y: .3, p: .5 }] }];
const first = await saveLocalNotebook(a, 0);
assert.equal(first.revision, 1);
assert.deepEqual((await loadLocalNotebook()).notebook, a);
const b = structuredClone(a), c = structuredClone(a);
b.books[0].title = "탭 B"; c.books[0].title = "탭 C";
const results = await Promise.allSettled([saveLocalNotebook(b,1), saveLocalNotebook(c,1)]);
assert.equal(results.filter(r=>r.status==="fulfilled").length, 1);
const rejected = results.find(r=>r.status==="rejected");
assert.ok(rejected.reason instanceof RevisionConflict);
const stored = await loadLocalNotebook();
assert.equal(stored.revision, 2);
assert.ok(["탭 B","탭 C"].includes(stored.notebook.books[0].title));
const old = newBookshelf();
delete old.books[0].pages[0].inkRows;
old.books[0].pages[0].strokes = a.books[0].pages[0].strokes;
const saved = await saveLocalNotebook(old,2);
const upgraded = await loadLocalNotebook();
assert.equal(upgraded.notebook.books[0].pages[0].inkRows,48);
assert.equal(upgraded.notebook.books[0].pages[0].strokes[0].points[0].y,.3*40/48);
await saveLocalNotebook(upgraded.notebook,saved.revision);
assert.deepEqual((await loadLocalNotebook()).notebook, upgraded.notebook);
await assert.rejects(()=>saveLocalNotebook(a,1), RevisionConflict);
assert.deepEqual((await loadLocalNotebook()).notebook, upgraded.notebook);
console.log("Local storage checks passed: reload preserves text/ink, atomic writes, stale-tab rejection and one-time old-ink migration.");

